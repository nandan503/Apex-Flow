-- Membership-backed RLS context: an arbitrary tenant setting is not authority.
CREATE FUNCTION authorized_tenant_id() RETURNS TEXT LANGUAGE sql STABLE SET search_path = pg_catalog, public AS $$
 SELECT tenant_id FROM public.memberships
 WHERE user_id = nullif(current_setting('app.principal_id', true), '')
 AND tenant_id = nullif(current_setting('app.tenant_id', true), '')
$$;
REVOKE ALL ON FUNCTION authorized_tenant_id() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION authorized_tenant_id() TO apex_app;

