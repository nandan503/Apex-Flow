 FOREIGN KEY (tenant_id, customer_id) REFERENCES customers(tenant_id, customer_id),
 FOREIGN KEY (tenant_id, driver_id) REFERENCES drivers(tenant_id, driver_id),
 CHECK ((role = 'CUSTOMER' AND customer_id IS NOT NULL AND driver_id IS NULL)
     OR (role = 'DRIVER' AND driver_id IS NOT NULL AND customer_id IS NULL)
     OR (role IN ('ADMIN','MANAGER') AND customer_id IS NULL AND driver_id IS NULL))
);
