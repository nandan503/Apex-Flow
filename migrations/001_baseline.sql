 tenant_id TEXT NOT NULL DEFAULT nullif(current_setting('app.tenant_id', true), '') REFERENCES tenants(tenant_id),
 notification_id TEXT NOT NULL, user_id TEXT NOT NULL REFERENCES users(user_id),
 read_at TIMESTAMPTZ NOT NULL DEFAULT now(), PRIMARY KEY (tenant_id, notification_id, user_id),
 FOREIGN KEY (tenant_id, notification_id) REFERENCES notifications(tenant_id, notification_id) ON DELETE CASCADE
);
ALTER TABLE notification_reads ENABLE ROW LEVEL SECURITY;
