CREATE TABLE customers (
        tenant_id TEXT NOT NULL DEFAULT nullif(current_setting('app.tenant_id', true), '') REFERENCES tenants(tenant_id),
        customer_id TEXT PRIMARY KEY,
        name TEXT NOT NULL,
