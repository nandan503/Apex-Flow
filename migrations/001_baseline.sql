CREATE POLICY own_notification_reads ON notification_reads
 USING (tenant_id = (SELECT authorized_tenant_id()) AND user_id = nullif(current_setting('app.principal_id',true),''))
 WITH CHECK (tenant_id = (SELECT authorized_tenant_id()) AND user_id = nullif(current_setting('app.principal_id',true),''));
GRANT SELECT, INSERT ON notification_reads TO apex_app;

CREATE TABLE idempotency_records (
 tenant_id TEXT NOT NULL DEFAULT nullif(current_setting('app.tenant_id', true), '') REFERENCES tenants(tenant_id),
 user_id TEXT NOT NULL REFERENCES users(user_id), key TEXT NOT NULL,
 fingerprint TEXT NOT NULL, authorization_context TEXT NOT NULL, state TEXT NOT NULL CHECK(state IN ('PENDING','COMPLETED','FAILED')),
 status_code INTEGER, response_body TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY (tenant_id, user_id, key),
 CHECK ((state = 'PENDING' AND status_code IS NULL AND response_body IS NULL)
 OR (state <> 'PENDING' AND status_code BETWEEN 200 AND 499 AND response_body IS NOT NULL))
);
